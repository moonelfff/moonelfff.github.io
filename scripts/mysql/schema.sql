CREATE TABLE IF NOT EXISTS site_content (
  `key` VARCHAR(255) NOT NULL PRIMARY KEY,
  value LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS tariffs (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  slug VARCHAR(255) NOT NULL UNIQUE,
  title TEXT NOT NULL,
  description_md LONGTEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS tariff_packages (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  tariff_id VARCHAR(64) NOT NULL,
  title TEXT NOT NULL,
  price_regular INT NOT NULL,
  price_discounted INT NULL,
  currency VARCHAR(16) NOT NULL DEFAULT '₽',
  sort_order INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_tariff_packages_tariff FOREIGN KEY (tariff_id)
    REFERENCES tariffs(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS psychological_tests (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  slug VARCHAR(255) NOT NULL UNIQUE,
  title TEXT NOT NULL,
  description LONGTEXT NOT NULL,
  version INT NOT NULL DEFAULT 1,
  schema_json LONGTEXT NOT NULL,
  scoring_json LONGTEXT NOT NULL,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
